"""Generate README.md from README-source.md.

Run from anywhere:  python py/make_readme.py
(The GitHub Action in .github/workflows/on-file-change.yml runs it whenever README-source.md changes.)

In README-source.md, a notebook link is written as

    [Label](Notebook.ipynb){Tooltip text}

where Notebook.ipynb is a file in the ipynb/ folder (spaces in the name are fine). It becomes a link to
the notebook on GitHub, with the tooltip shown on hover, followed by a Colab icon that runs it in Colab.
Notebook links that are separated only by spaces or a single line break are joined with " · ".
Everything else in README-source.md (ordinary Markdown and HTML) is copied to README.md unchanged.
"""

import html
import re
import sys
import urllib.parse
from pathlib import Path

ROOT      = Path(__file__).resolve().parent.parent
SOURCE    = ROOT / 'README-source.md'
TARGET    = ROOT / 'README.md'
NOTEBOOKS = 'ipynb/'
COLAB     = 'https://colab.research.google.com/github/norvig/pytudes/blob/main/ipynb/'
ICON      = 'https://colab.research.google.com/img/colab_favicon_256px.png'
SEPARATOR = ' &nbsp;·&nbsp; '

NOTE = '<!-- Generated by py/make_readme.py from README-source.md. Edit that file, not this one. -->\n'

# [Label](file.ipynb){tooltip}
LINK = r'\[([^\]\n]+)\]\(([^)\n]+?\.ipynb)\)\{([^}\n]*)\}'
# A run of LINKs separated by blanks or a single line break.
RUN  = re.compile(rf'{LINK}(?:[ \t]*\n?[ \t]*{LINK})*')


def notebook_link(label: str, file: str, tooltip: str) -> str:
    """HTML for one notebook: the title link (to GitHub) followed by the Colab icon link."""
    name  = urllib.parse.unquote(file.strip())
    path  = urllib.parse.quote(name)
    title = re.match(r'(.*?) \(\d{4}\): ', tooltip) or re.match(r'(.*?): ', tooltip)
    title = title.group(1) if title else label
    return (f'<a href="{NOTEBOOKS}{path}" title="{html.escape(tooltip)}">{label}</a>&nbsp;'
            f'<a href="{COLAB}{path}" title="Run &quot;{html.escape(title)}&quot; in Colab">'
            f'<img src="{ICON}" height="14" alt="[colab]"></a>')


def expand(text: str) -> tuple:
    """Expand every run of notebook links in `text`; also return the notebook files mentioned."""
    files = []
    def run(match) -> str:
        links = re.findall(LINK, match.group(0))
        files.extend(urllib.parse.unquote(f.strip()) for _, f, _ in links)
        return SEPARATOR.join(notebook_link(*link) for link in links)
    return RUN.sub(run, text), files


def main() -> None:
    source = SOURCE.read_text(encoding='utf-8')
    source = re.sub(r'\A\s*<!--.*?-->\n', '', source, flags=re.S)  # drop the source file's own header comment
    readme, files = expand(source)
    missing = sorted({f for f in files if not (ROOT / NOTEBOOKS / f).exists()})
    if missing:
        sys.exit(f'README-source.md links to notebooks that are not in {NOTEBOOKS}: {", ".join(missing)}')
    leftover = re.findall(r'\]\([^)\n]*\.ipynb\)\{', readme)
    if leftover:
        sys.exit(f'Could not parse {len(leftover)} notebook link(s); check for a missing "}}" or a line break inside a link.')
    TARGET.write_text(NOTE + readme, encoding='utf-8')
    print(f'Wrote {TARGET.name} with {len(files)} notebook links.')


if __name__ == '__main__':
    main()
